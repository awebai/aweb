#!/usr/bin/env python3
"""Generate the public description and Go's pinned codec/binding selection."""

import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

from aweb_naapp.runtime.protected_signer.catalog import OPERATIONS, operation_description

ROOT = Path(__file__).resolve().parents[1]


def generated():
    description = operation_description()
    public = json.dumps(description, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    digest = hashlib.sha256(public.encode()).hexdigest()
    lines = ["// Code generated by scripts/generate_protected_operations.py; DO NOT EDIT.",
        "package handoff", "", f'const protectedOperationsDescriptionSHA256 = "{digest}"', "",
        "var generatedPreparedShapes = map[string]preparedShape{"]
    for row in description["operations"]:
        verifier = OPERATIONS[(row["operation"], row["variant"])].codec.go_verifier
        if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9]+", verifier):
            raise ValueError("definition needs an existing consumer codec verifier")
        selector = row["operation"] + "|" + row["variant"]
        added = ", ".join(json.dumps(name) for name in row["prepared_fields"])
        paths = ", ".join(json.dumps(path) for path in row["bindings"].values())
        lines.append(f'{json.dumps(selector)}: {{added: []string{{{added}}}, check: {verifier}, bindings: []string{{{paths}}}}},')
    lines.extend(["}", "", "var generatedDisplays = map[string]operationDisplay{"])
    for row in description["operations"]:
        display = row["display"]
        rows = lambda pairs: ", ".join(  # noqa: E731
            "{" + json.dumps(key) + ", " + json.dumps(source) + "}" for key, source in pairs.items())
        consequences = ", ".join(json.dumps(line) for line in display["consequences"])
        refusals = ", ".join(json.dumps(code) + ": " + json.dumps(text) for code, text in display["refusals"].items())
        lines.append(f'{json.dumps(row["operation"] + "|" + row["variant"])}: {{title: {json.dumps(display["title"])}, '
            f'consequences: []string{{{consequences}}}, names: []displayRow{{{rows(display["names"])}}}, '
            f'technical: []displayRow{{{rows(display["technical"])}}}, refusals: map[string]string{{{refusals}}}}},')
    lines.extend(["}", ""])
    # Generated constant is shared with CLI callers of the root codec. Its one
    # authored value lives in the root definition's display metadata.
    statements = {spec.display.responsibility_statement for spec in OPERATIONS.values()} - {None}
    if len(statements) != 1:
        raise ValueError("the existing root codec needs its one responsibility statement")
    lines.append("// RootResponsibilityStatement states what the root's human accepts.")
    lines.append("const RootResponsibilityStatement = " + json.dumps(statements.pop()))
    source = subprocess.run(["gofmt"], input="\n".join(lines) + "\n", text=True, check=True,
        capture_output=True).stdout
    return {ROOT / "docs/protected-operations-v1.json": public,
        ROOT / "cli/go/internal/handoff/protected_operations_generated.go": source}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in generated().items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"stale generated operation definition: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print("Protected operation description and Go table match definitions")


if __name__ == "__main__":
    main()
